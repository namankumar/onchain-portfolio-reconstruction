"""Catalog Python source without importing or executing investigation modules."""
import argparse
import ast
import json
from pathlib import Path


def category(name):
    if "derive_wallet" in name or "wallet_derivation" in name or "wallet_recovery_debug" in name:
        return "Wallet address derivation (private workflow)"
    if name.startswith(("validate_", "test_")) or "regression" in name:
        return "Verification and regression checks"
    if any(term in name for term in ("price", "rebound", "depeg")):
        return "Market history and valuation"
    if any(term in name for term in ("simulation", "preview", "exit", "quotes", "sale_wire", "sale_prepare")) and "report" not in name:
        return "Unsigned evaluation and route simulation"
    if "report" in name or name == "dated_tables.py":
        return "Evidence-backed reporting"
    if any(term in name for term in ("reconstruct", "trace", "ledger", "history", "outgoing_audit", "withdrawal_email", "tax_sources")):
        return "Transaction and export reconstruction"
    return "Chain and protocol discovery"


def catalog(source):
    entries = []
    for path in sorted(source.glob("*.py")):
        data = path.read_bytes()
        tree = ast.parse(data, filename=path.name)
        imports = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                imports.update(alias.name.split(".")[0] for alias in node.names)
            elif isinstance(node, ast.ImportFrom) and node.module:
                imports.add(node.module.split(".")[0])
        strings = [n.value for n in ast.walk(tree) if isinstance(n, ast.Constant) and isinstance(n.value, str)]
        # This is a public scope manifest, not a map back to a private investigation.
        # Original filenames can contain address fragments, private workflow clues, or other
        # context that does not belong in a standalone release.
        entries.append({"entry_id": f"source-{len(entries) + 1:03d}",
                        "category": category(path.name), "lines": len(data.splitlines()),
                        "import_count": len(imports),
                        "has_machine_local_path": any("/Users/" in s or "/Downloads/" in s for s in strings),
                        "portable_command": False,
                        "status": "Original investigation source; requires its inputs, configuration and dependency review"})
    return entries


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    rows = catalog(args.source)
    if not rows:
        parser.error("No Python sources found")
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "source-catalog.json").write_text(json.dumps({"scripts": len(rows), "lines": sum(r["lines"] for r in rows), "entries": rows}, indent=2) + "\n")
    lines = ["# Opaque scope manifest", "", f"{len(rows)} scripts, {sum(r['lines'] for r in rows):,} lines. Generated by AST inspection, without importing any module.",
             "", "This manifest records the source base's technical scale without claiming that all scripts are portable or freshly tested. The standalone package contains only reviewed extractions. Each opaque entry represents one original script; filenames, hashes and local paths are deliberately excluded.", ""]
    for group in sorted({r["category"] for r in rows}):
        selected = [r for r in rows if r["category"] == group]
        lines.extend([f"## {group} ({len(selected)})", "", "| Opaque entry | Lines | Import count | Machine-local path literal |", "| --- | --- | --- | --- |"])
        for row in selected:
            lines.append(f"| `{row['entry_id']}` | {row['lines']} | {row['import_count']} | {row['has_machine_local_path']} |")
        lines.append("")
    (args.out / "source-catalog.md").write_text("\n".join(lines))
    print(json.dumps({"scripts": len(rows), "lines": sum(r["lines"] for r in rows)}))


if __name__ == "__main__":
    main()
